import assert from "node:assert/strict";
import { fixture } from "./purchase-fixture.mjs";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, headless: true, args: ["--no-sandbox"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
try {
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  const base = process.env.COMPASS_BASE_URL || "http://127.0.0.1:3101";
  await page.goto(base);
  await page.waitForFunction(() => !document.querySelector(".page-heading button").disabled);
  await page.getByRole("button", { name: "미래", exact: true }).click();
  const purchase = page.getByRole("region", { name: "부동산 매매", exact: true });
  assert.equal(await purchase.getByRole("heading", { name: "나의 매매 계획을 시작해요" }).count(), 1);
  assert.equal(await purchase.locator(".purchase-summary").count(), 0);
  const p = fixture();
  p.name = "테스트 매매";
  page.once("dialog", d => d.accept());
  await purchase.locator("input[type=file]").setInputFiles({ name: "private.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(p)) });
  await purchase.getByRole("heading", { name: /테스트 매매/ }).waitFor();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem("compass-v0.1")).purchase?.name === "테스트 매매");
  assert.match(await purchase.locator(".purchase-summary").innerText(), /11,200/);
  assert.match(await purchase.locator(".purchase-summary").innerText(), /기준 미확인/);
  await purchase.getByRole("button", { name: "매매 설정", exact: true }).click();
  const settings = page.getByRole("form", { name: "매매 설정 편집" });
  await settings.getByLabel("재원 합계의 기납부 기준").selectOption("after-paid");
  await settings.getByRole("button", { name: "기록 저장" }).click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem("compass-v0.1")).purchase.basis === "after-paid");
  await purchase.getByRole("button", { name: "미입력 주식 수정", exact: true }).click();
  const funding = page.getByRole("form", { name: "재원 편집" });
  assert.equal(await funding.getByLabel("예상 투입금액 (원)", { exact: true }).inputValue(), "");
  await funding.getByLabel("예상 투입금액 (원)", { exact: true }).fill("0");
  await funding.getByRole("button", { name: "기록 저장" }).click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem("compass-v0.1")).purchase.funding.find(f => f.id === "stock").expected === 0);
  await purchase.getByRole("button", { name: "잔금·부대비용 수정", exact: true }).click();
  const payment = page.getByRole("form", { name: "납부 일정 편집" });
  await payment.getByLabel("납부 상태", { exact: true }).selectOption("partial");
  await payment.getByLabel("실제 납부일", { exact: true }).fill("2030-02-01");
  await payment.getByLabel("실제 납부금액 (원)", { exact: true }).fill("500");
  await payment.getByRole("button", { name: "기록 저장" }).click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem("compass-v0.1")).purchase.payments[1].actualAmount === 500);
  const original = await page.evaluate(() => JSON.parse(localStorage.getItem("compass-v0.1")).purchase);
  await purchase.getByRole("button", { name: "시뮬레이션 열기", exact: true }).click();
  let simulation = page.getByRole("region", { name: "시뮬레이션", exact: true });
  await simulation.getByLabel("대출 예상 투입 (원)", { exact: true }).fill("9000");
  await simulation.getByLabel("세금 납부방식", { exact: true }).selectOption("card");
  await simulation.getByLabel("총 할부수수료 (원)", { exact: true }).fill("100");
  assert.match(await simulation.innerText(), /2,200/);
  await simulation.getByRole("button", { name: "시나리오 저장", exact: true }).click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem("compass-v0.1")).purchase.scenario?.funding[0].amount === 9000);
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem("compass-v0.1")));
  assert.deepEqual(saved.purchase.funding, original.funding);
  assert.deepEqual(saved.purchase.payments, original.payments);
  assert.deepEqual(saved.purchase.costs, original.costs);
  await page.reload();
  await page.waitForFunction(() => !document.querySelector(".page-heading button").disabled);
  await page.getByRole("button", { name: "미래", exact: true }).click();
  await purchase.getByRole("button", { name: "시뮬레이션 열기", exact: true }).click();
  simulation = page.getByRole("region", { name: "시뮬레이션", exact: true });
  assert.equal(await simulation.getByLabel("대출 예상 투입 (원)", { exact: true }).inputValue(), "9000");
  const downloaded = page.waitForEvent("download");
  await page.getByRole("button", { name: "백업 내보내기", exact: true }).click();
  const download = await downloaded;
  const stream = await download.createReadStream();
  let backup = ""; for await (const chunk of stream) backup += chunk;
  assert.deepEqual(JSON.parse(backup).purchase, saved.purchase);
  await purchase.locator("input[type=file]").setInputFiles({ name: "invalid.json", mimeType: "application/json", buffer: Buffer.from('{"version":1}') });
  await purchase.getByRole("status").filter({ hasText: /형식/ }).waitFor();
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem("compass-v0.1")).purchase), saved.purchase);
  for (const width of [375, 768]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `overflow at ${width}`);
  }
  assert.deepEqual(errors, []);
  console.log("PASS: private import, records, unknown vs zero, basis selection, isolated saved simulation, reload, full backup, invalid import protection, mobile overflow");
} catch (error) {
  console.error("Synthetic editor diagnostics:", await page.locator(".purchase-editor").innerText().catch(() => "no editor"));
  throw error;
} finally { await browser.close(); }
